// Get saved language preference or detect from browser
const getInitialLanguage = (): string => {
  // Check localStorage first
  const savedLang = localStorage.getItem("i18nextLng");
  if (savedLang && (savedLang === "en" || savedLang === "ar")) {
    return savedLang;
  }
  
  // Fallback to browser language detection
  const browserLang =
    navigator.language ||
    (navigator as Navigator & { userLanguage?: string }).userLanguage;
  if (browserLang && browserLang.startsWith("ar")) {
    return "ar";
  }
  
  // Default to English
  return "en";
};

// Set document direction based on language
const setDocumentDirection = (lang: string) => {
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = lang;
};

// Initialize language
const initialLang = getInitialLanguage();
setDocumentDirection(initialLang);

// English ships in the main bundle (it is also the fallback). Arabic is a separate
// file fetched the first time it is needed: at start-up for someone whose language
// is Arabic, or when anyone switches to it. i18next waits for it before it reports
// the change, so the screens never flash the wrong language.
const lazyLanguages = {
  type: "backend" as const,
  init() {},
  read(language: string, _namespace: string, callback: (error: unknown, data: unknown) => void) {
    if (language !== "ar") {
      callback(null, {});
      return;
    }
    import("./i18n.ar").then(
      (module) => callback(null, module.default.translation),
      (error) => callback(error, null),
    );
  },
};

/** Resolves once the starting language's text is loaded. Render the app after it. */
export const i18nReady = i18n
  .use(lazyLanguages)
  .use(initReactI18next)
  .init({
    resources,
    partialBundledLanguages: true,
    lng: initialLang,
    fallbackLng: "en",
    interpolation: { escapeValue: false },
    react: {
      useSuspense: false, // Disable suspense to avoid issues
    },
  });

// Listen for language changes and update localStorage and direction
i18n.on("languageChanged", (lng) => {
  localStorage.setItem("i18nextLng", lng);
  setDocumentDirection(lng);
});

export default i18n;
