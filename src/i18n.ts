// Get saved language preference or detect from browser
const getInitialLanguage = (): string => {
  // Check localStorage first
  const savedLang = localStorage.getItem("i18nextLng");
  if (savedLang && (savedLang === "en" || savedLang === "ar")) {
    return savedLang;
  }
  
  // Fallback to browser language detection
  const browserLang =
    navigator.language ||
    (navigator as Navigator & { userLanguage?: string }).userLanguage;
  if (browserLang && browserLang.startsWith("ar")) {
    return "ar";
  }
  
  // Default to English
  return "en";
};

// Set document direction based on language
const setDocumentDirection = (lang: string) => {
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = lang;
};

// Initialize language
const initialLang = getInitialLanguage();
setDocumentDirection(initialLang);

i18n.use(initReactI18next).init({
  resources,
  lng: initialLang,
  fallbackLng: "en",
  interpolation: { escapeValue: false },
  react: {
    useSuspense: false, // Disable suspense to avoid issues
  },
});

// Listen for language changes and update localStorage and direction
i18n.on("languageChanged", (lng) => {
  localStorage.setItem("i18nextLng", lng);
  setDocumentDirection(lng);
});

export default i18n;
