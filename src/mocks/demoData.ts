/** Map DB trainer row to Trainers page UI shape */
export function mapDbTrainerToUI(t: (typeof DEMO_TRAINERS)[0]) {
  const statusMap: Record<string, "active" | "inactive" | "busy" | "available"> = {
    active: "active",
    inactive: "inactive",
    on_leave: "busy",
  };
  return {
    id: t.id,
    name: `${t.first_name} ${t.last_name}`,
    email: t.email,
    phone: t.phone ?? "",
    specialty: (t.specialties as string[])?.[0] ?? "General",
    rating: Number(t.rating) || 4.5,
    status: statusMap[t.status] ?? "active",
    classes: DEMO_CLASSES.filter((c) => c.trainer_id === t.id).length,
    experience: "3+ years",
    avatar: "",
  };
}
